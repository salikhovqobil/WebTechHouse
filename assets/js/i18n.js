const STORAGE_KEY = "techhouse_lang";
const DEFAULT_LANG = "uz";

const resolveLanguage = (lang) => {
    if (!lang) {
        return DEFAULT_LANG;
    }
    return translations[lang] ? lang : DEFAULT_LANG;
};

let currentLang = resolveLanguage(localStorage.getItem(STORAGE_KEY));

export const getLanguage = () => currentLang;

export const setLanguage = (lang) => {
    currentLang = resolveLanguage(lang);
    localStorage.setItem(STORAGE_KEY, currentLang);
};

const applyVars = (value, vars) => {
    if (!vars || typeof value !== "string") {
        return value;
    }
    return value.replace(/\{\{(\w+)\}\}/g, (match, key) => {
        if (Object.prototype.hasOwnProperty.call(vars, key)) {
            return String(vars[key]);
        }
        return match;
    });
};

export const t = (key, vars = {}) => {
    const dict = translations[currentLang] || translations[DEFAULT_LANG] || {};
    const fallback = translations[DEFAULT_LANG] || {};
    const value = dict[key] || fallback[key] || key;
    return applyVars(value, vars);
};

export const applyTranslations = (lang = currentLang) => {
    setLanguage(lang);
    document.documentElement.lang = currentLang;

    document.querySelectorAll("[data-i18n]").forEach((el) => {
        const key = el.dataset.i18n;
        if (key) {
            el.textContent = t(key);
        }
    });

    document.querySelectorAll("[data-i18n-html]").forEach((el) => {
        const key = el.dataset.i18nHtml;
        if (key) {
            el.innerHTML = t(key);
        }
    });

    document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
        const key = el.dataset.i18nPlaceholder;
        if (key) {
            el.setAttribute("placeholder", t(key));
        }
    });

    document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
        const key = el.dataset.i18nAria;
        if (key) {
            el.setAttribute("aria-label", t(key));
        }
    });

    document.querySelectorAll("[data-i18n-alt]").forEach((el) => {
        const key = el.dataset.i18nAlt;
        if (key) {
            el.setAttribute("alt", t(key));
        }
    });
};

export const initLanguageSwitcher = () => {
    const buttons = document.querySelectorAll(".lang-btn");
    if (!buttons.length) {
        return;
    }

    const applyActive = () => {
        buttons.forEach((button) => {
            const isActive = button.dataset.lang === currentLang;
            button.classList.toggle("active", isActive);
            button.setAttribute("aria-pressed", isActive ? "true" : "false");
        });
    };

    applyActive();

    buttons.forEach((button) => {
        button.addEventListener("click", () => {
            const lang = button.dataset.lang;
            if (!lang || lang === currentLang) {
                return;
            }
            setLanguage(lang);
            window.location.reload();
        });
    });
};
